/** Translate SQLite-oriented SQL used by EventGo into PostgreSQL. */

const UTC_NOW = "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC')";
const NOW_TEXT = `to_char(${UTC_NOW},'YYYY-MM-DD HH24:MI:SS')`;

/** SQLite sums booleans as 0/1; PostgreSQL needs an explicit cast. Handles nested parentheses. */
function wrapBooleanSums(sql) {
  let out = '', i = 0;
  const re = /\bsum\(/gi;
  let m;
  while ((m = re.exec(sql))) {
    const start = m.index + m[0].length;
    let depth = 1, j = start, quote = false;
    for (; j < sql.length && depth; j++) {
      const ch = sql[j];
      if (ch === "'") quote = !quote;
      else if (!quote && ch === '(') depth++;
      else if (!quote && ch === ')') depth--;
    }
    const inner = sql.slice(start, j - 1);
    const stripped = inner.replace(/'[^']*'/g, "''");
    out += sql.slice(i, start);
    out += /[=<>]|\bAND\b|\bOR\b/i.test(stripped) ? `(CASE WHEN ${inner} THEN 1 ELSE 0 END)` : inner;
    out += ')';
    i = j;
    re.lastIndex = j;
  }
  return out + sql.slice(i);
}

export function toPostgres(sql) {
  let text = sql;
  text = text.replace(/INSERT OR IGNORE INTO\s+(\w+)\s*\(([^)]+)\)\s*VALUES\s*\(([^)]+)\)/gi,
    (_, table, cols, vals) => {
      const conflict = conflictTarget(table, cols);
      return `INSERT INTO ${table} (${cols}) VALUES (${vals})${conflict ? ` ON CONFLICT ${conflict} DO NOTHING` : ''}`;
    });
  text = text.replace(/INSERT OR IGNORE INTO\s+(\w+)\s+VALUES\s*\(([^)]+)\)/gi,
    (_, table, vals) => {
      const conflict = conflictTarget(table, '');
      return `INSERT INTO ${table} VALUES (${vals})${conflict ? ` ON CONFLICT ${conflict} DO NOTHING` : ''}`;
    });
  text = text.replace(/date\('now',\s*'\+9 hours'\)/gi,
    `to_char(${UTC_NOW} + INTERVAL '9 hours','YYYY-MM-DD')`);
  text = text.replace(/datetime\('now',\s*'-1 day'\)/gi,
    `to_char(${UTC_NOW} - INTERVAL '1 day','YYYY-MM-DD HH24:MI:SS')`);
  text = text.replace(/datetime\('now'\)/gi, NOW_TEXT);
  text = text.replace(/date\(\?,\s*'\+1 day'\)/gi, "to_char(CAST(? AS date) + 1,'YYYY-MM-DD')");
  text = wrapBooleanSums(text);
  text = text.replace(/\bBEGIN IMMEDIATE\b/gi, 'BEGIN');
  let n = 0;
  text = text.replace(/\?/g, () => `$${++n}`);
  return text;
}

function conflictTarget(table, cols) {
  const c = cols.replace(/\s+/g, '').toLowerCase();
  switch (table.toLowerCase()) {
    case 'app_settings': return '(key)';
    case 'guest_answers': return '(guest_id, field_id)';
    case 'chat_messages': return '(event_id, user_id, client_token)';
    case 'ai_turns': return '(event_id, user_id, client_token)';
    case 'notification_state': return '(user_id)';
    default:
      if (c.includes('key') && table.toLowerCase() === 'app_settings') return '(key)';
      return null;
  }
}

export function shouldReturnId(sql) {
  return /^\s*INSERT\b/i.test(sql) && !/\bON CONFLICT\b/i.test(sql) && !/\bRETURNING\b/i.test(sql)
    && !/\bDO NOTHING\b/i.test(sql) && !/\bDO UPDATE\b/i.test(sql);
}

